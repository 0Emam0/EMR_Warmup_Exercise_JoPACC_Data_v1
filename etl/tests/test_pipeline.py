def test_native_page_values_and_units(cfg, pdfs):
    found, method = values_on_page(_find(pdfs, "august_monthly_report_2026"), 9, cfg)
    assert method == "native"
    by_value = {m.value: m for m in found}
    assert 162_180_000 in by_value
    assert 16_640_000_000 in by_value
    assert by_value[16_640_000_000].unit == "JOD", "subscript JOD must attach"


def test_ocr_page_recovers_bar_values_and_dates_them(cfg, pdfs):
    """The April 2025 report has no text layer. Bars read 1.74/1.78/1.81 M."""
    found, method = values_on_page(_find(pdfs, "april_monthly_report_2025"), 10, cfg)
    assert method == "ocr"
    dated = {m.label_period: m.value for m in found if m.label_period}
    assert dated.get("2025-02") == pytest.approx(1_740_000)
    assert dated.get("2025-03") == pytest.approx(1_780_000)
    assert dated.get("2025-04") == pytest.approx(1_810_000)


def test_decimal_points_survive_ocr(cfg, pdfs):
    """1.74 M must not come back as 174M -- a hundredfold error."""
    found, _ = values_on_page(_find(pdfs, "april_monthly_report_2025"), 10, cfg)
    assert not any(m.value and m.value > 10_000_000 for m in found)


def test_inline_category_labels(cfg, pdfs):
    """Category and value share a baseline: '95.9% Jordanian 2.29M'."""
    found, _ = values_on_page(_find(pdfs, "august_monthly_report_2026"), 11, cfg)
    labelled = {(m.label, m.value) for m in found}
    assert ("Jordanian", 95.9) in labelled
    assert ("Non-Jordanian", 4.1) in labelled


def test_rotated_labels_on_quarterly_poster(cfg, pdfs):
    """Bar rows are labelled with sideways 'Q1 2026' / 'Q4 2025'."""
    found, _ = values_on_page(_find(pdfs, "quarterly_report_q1_2026"), 2, cfg)
    periods = {m.label_period for m in found}
    assert "2026-Q1" in periods
    assert "2025-Q4" in periods
    percents = [m.value for m in found if m.unit == "percent"]
    assert 81.3 in percents, "percent sign must not be stripped as ornament"


def test_headline_numerals_are_not_loaded_as_measurements(cfg, pdfs):
    """'Since the Beginning of 2026' is prose, not a figure."""
    found, _ = values_on_page(_find(pdfs, "august_monthly_report_2026"), 9, cfg)
    assert 2026 not in [m.value for m in found]


