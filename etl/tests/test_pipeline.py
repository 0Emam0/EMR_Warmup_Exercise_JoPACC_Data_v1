def test_sections_discovered_per_file(cfg, pdfs):
    from jopacc_etl.pipeline import process
    record = inv.register(_find(pdfs, "august_monthly_report_2026"), cfg)
    result = process(record, cfg)
    keys = {s.key for s in result.sections}
    assert {"cliq", "jomopay", "efawateercom", "ach", "eccu"} <= keys
    assert result.status in ("ok", "partial")
    assert result.measurements


def test_workbook_is_written_with_audit_sheets(cfg, pdfs, tmp_path):
    import openpyxl
    from jopacc_etl.load.excel import write_workbook
    from jopacc_etl.pipeline import process
    record = inv.register(_find(pdfs, "august_monthly_report_2026"), cfg)
    path = write_workbook(process(record, cfg), cfg, tmp_path)
    book = openpyxl.load_workbook(path)
    assert {"Measurements", "Metadata", "Validation", "Page_Log",
            "Unparsed", "Sections"} <= set(book.sheetnames)
    assert book["Measurements"].max_row > 1


def test_failed_page_is_recorded_not_swallowed(cfg, pdfs, monkeypatch):
    """A page that raises must appear in the log, and the report must survive."""
    from jopacc_etl import pipeline

    calls = {"n": 0}
    real = pipeline.extract_tokens

    def flaky(page, config):
        calls["n"] += 1
        if calls["n"] == 3:
            raise RuntimeError("simulated reader failure")
        return real(page, config)

    monkeypatch.setattr(pipeline, "extract_tokens", flaky)
    record = inv.register(_find(pdfs, "quarterly_report_q1_2026"), cfg)
    result = pipeline.process(record, cfg)
    failed = [p for p in result.page_log if p["status"] == "failed"]
    assert len(failed) == 1
    assert "simulated reader failure" in failed[0]["error"]
    assert result.status == "partial"
