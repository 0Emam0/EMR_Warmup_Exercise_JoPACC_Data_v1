@pytest.mark.parametrize("literal,expected,unit", [
    ("1.81 M", 1_810_000, "count"),
    ("162.18M", 162_180_000, "count"),
    ("2.43B JOD", 2_430_000_000, "JOD"),
    ("16.64BJOD", 16_640_000_000, "JOD"),   # subscript currency, glued on
    ("130 JOD", 130, "JOD"),                # currency with no scale suffix
    ("98.6K", 98_600, "count"),
    ("5.3%", 5.3, "percent"),
    ("2,601", 2601, "count"),
])
def test_value_parsing(literal, expected, unit):
    parsed = parse_value(literal)
    assert parsed.parse_ok
    assert parsed.value == pytest.approx(expected)
    assert parsed.unit == unit


def test_ocr_character_repair_is_reported():
    parsed = parse_value("l.8l M")
    assert parsed.value == pytest.approx(1_810_000)
    assert parsed.ocr_repaired, "a repaired reading must say so"


def test_unrecognised_literal_is_not_guessed():
    assert parse_value("garbage").value is None


@pytest.mark.parametrize("label,expected", [
    ("Apr-25", "2025-04"), ("Q1 2026", "2026-Q1"), ("2024", "2024"),
])
def test_period_labels(label, expected):
    assert parse_period_label(label) == expected


