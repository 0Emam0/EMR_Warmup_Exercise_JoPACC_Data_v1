"""Tests against the real reports.

These assert figures read off the rendered pages by eye, so a regression in
extraction shows up as a wrong number rather than as a passing test over a
fixture that was generated by the same code it is meant to check.

Set JOPACC_PDF_DIR if the reports live somewhere other than the configured
input directory.
"""

from __future__ import annotations

import os
from pathlib import Path

import pymupdf
import pytest

from jopacc_etl.config import load_config
from jopacc_etl.discovery import inventory as inv
from jopacc_etl.extraction import layout as L
from jopacc_etl.extraction.tokens import extract_tokens
from jopacc_etl.transform.numbers import parse_period_label, parse_value

CONFIG = Path(__file__).resolve().parent.parent / "config" / "config.yaml"


@pytest.fixture(scope="session")
def cfg():
    config = load_config(CONFIG)
    override = os.environ.get("JOPACC_PDF_DIR")
    if override:
        config["paths"]["input_dir"] = Path(override)
    return config


@pytest.fixture(scope="session")
def pdfs(cfg):
    found = {p.name: p for p in Path(cfg["paths"]["input_dir"]).rglob("*.pdf")}
    if not found:
        pytest.skip("no PDFs in the configured input directory")
    return found


def _find(pdfs, fragment):
    for name, path in pdfs.items():
        if fragment in name:
            return path
    pytest.skip(f"no PDF matching {fragment!r}")


def values_on_page(path, page_index, cfg):
    doc = pymupdf.open(path)
    page = doc[page_index]
    tokens, method = extract_tokens(page, cfg)
    tokens, _ = L.drop_decorative(tokens)
    upright, rotated = L.split_orientation(tokens)
    rotated = [t for t in rotated if parse_period_label(t.text)]
    lines = L.build_lines(upright, cfg)
    content, _ = L.strip_furniture(lines, page.rect.height, page.rect.width, cfg)
    panels = L.split_panels(content, page.rect.height, cfg)
    axis = L.page_axis_labels(panels)
    out = []
    for panel in panels:
        out += L.measure_panel(panel, page.rect.width, cfg, axis, rotated)
    doc.close()
    return out, method


